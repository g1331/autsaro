class ActualCAnalysisTests(unittest.TestCase):
    def project(self, root: Path, source: str, source_name: str = "bsw/src/main.c", extra_files: dict[str, str] | None = None,
                unbuilt: tuple[str, ...] = (), *, pedantic: bool = True) -> Path:
        project = root / "sources"
        project.mkdir()
        target = "windows-x64-controlled-v1" if platform.system() == "Windows" else "linux-x64-controlled-v1"
        abi = "x86_64-w64-mingw32" if platform.system() == "Windows" else "x86_64-linux-gnu"
        extra_files = extra_files or {}
        files = {**extra_files, source_name: source, "target.json": json.dumps({
            "format": "autosar-build-target-v4", "target": target, "abi": abi, "profile": "host",
            "compilerFlags": ["-std=c99", "-Wall", "-Wextra", "-Werror", *(["-pedantic"] if pedantic else [])],
            "sources": [source_name, *(name for name in extra_files if name.endswith(".c") and name not in unbuilt)],
            "includePaths": ["."]})}
        for name, text in files.items():
            path = project / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        (project / "meta").mkdir(exist_ok=True)
        (project / "meta/files.list").write_text("\n".join(sorted(files)) + "\n", encoding="utf-8")
        (project / "meta/files.sha256").write_text("".join(f"{hashlib.sha256((project / name).read_bytes()).hexdigest()}  {name}\n" for name in [*sorted(files), "meta/files.list"]), encoding="utf-8")
        return project

    def gate_project(self, root: Path, source: str, debug: bool, *,
                     extra_files: dict[str, str] | None = None,
                     fixture_inputs: tuple[Path, ...] = (), ecu: bool = False) -> Path:
        root.mkdir()
        kernel = "/* Include-only kernel fixture. */\n"
        # Both sides are generated by this test, even on a PR merge checkout.
        producers = (Path(__file__).resolve(), *fixture_inputs)
        project = self.project(root, source, extra_files={
            **(extra_files or {}),
            "kernel/kernel.h": kernel,
            "meta/integration.json": json.dumps({
                "originalBswSources": {},
                "plan": {"sources": [{"logicalPath": "fixture"}],
                         "runtimeSources": {path.relative_to(c_baseline.ROOT).as_posix(): c_gate.sha(path)
                                            for path in producers},
                         "ruleSetIdentity": {"release": "R24-11", "rulesVersion": "1"}},
            }),
        })
        target = c_gate.read(project / "target.json")
        delivery = {"producerVersion": "0.1.0", "profileId": "singlecore-ecu-v1"}
        kernel_root = project / "kernel"
        target.update(entries={"target": None}, nativeDelivery=delivery, kernelSha256={
            path.relative_to(kernel_root).as_posix(): c_gate.sha(path)
            for path in sorted(kernel_root.rglob("*")) if path.is_file()
        })
        if ecu:
            entries = {"host-batch": "integration/src/ecu_host_batch.c", "probe": "integration/src/ecu_probe.c"}
            kernel_sources = [name for name in target["kernelSha256"] if name.endswith(".c")]
            target.update(profile="ecu", hostBatchProtocol="HostBatchV2", canFrameProfile="classical-and-fd", entries=entries,
                          kernelSources=kernel_sources, kernelPatches=[])
            target["sources"] = [name for name in target["sources"]
                                 if name not in entries.values() and not name.startswith("kernel/")]
            target["compilerFlags"].append("-fexceptions")
        if debug:
            target["compilerFlags"].append("-g")
        (project / "target.json").write_text(json.dumps(target), encoding="utf-8")
        inventory_path = project / "meta/files.list"
        payload = {name: c_gate.sha(project / name)
                   for name in inventory_path.read_text(encoding="utf-8").splitlines()}
        # The rename proof consumes both canonical carriers from a native package.
        seal_policy = "meta/seal-policy.json"
        ownership = "meta/workbench-ownership.json"
        owner = {"owner": "generated", "producerId": "autosar-generator"}
        policy = dict.fromkeys([*payload, seal_policy], owner)
        (project / seal_policy).write_bytes((json.dumps(
            {"metadata": delivery, "payload": payload, "policy": policy}, indent=2, sort_keys=True) + "\n").encode())
        ledger = {"formatVersion": 3, **delivery, "files": [
            {"path": name, **fields, "sha256": c_gate.sha(project / name)}
            for name, fields in sorted(policy.items())
        ]}
        (project / ownership).write_bytes((json.dumps(ledger, indent=2) + "\n").encode())
        inventory = sorted([*policy, ownership])
        inventory_path.write_text("\n".join(inventory) + "\n", encoding="utf-8")
        (project / "meta/files.sha256").write_text("".join(
            f"{c_gate.sha(project / name)}  {name}\n" for name in [*inventory, "meta/files.list"]),
            encoding="utf-8")
        return project

    def gate_scope(self, directory: Path, side: str, summary: dict, sample: str) -> None:
        for target in c_gate.TARGETS:
            for other_sample in c_gate.SAMPLES:
                path = directory / f"c-analysis-scope-{side}-{target}-{other_sample}-0" / other_sample
                path.mkdir(parents=True, exist_ok=True)
                if target == summary["scope"]["target"] and other_sample == sample:
                    receipt = c_comparison.scope_receipt(summary, sample)
                else:
                    unit = "stub.c"
                    receipt = {
                        "format": "c-misra-scope-input-v1", "sample": other_sample, "target": target,
                        "analysisIdentity": hashlib.sha256(f"{target}/{other_sample}".encode()).hexdigest(),
                        "translationUnits": [unit], "projectTranslationUnits": {unit: [unit]},
                    }
                (path / "scope-input.json").write_text(json.dumps(receipt), encoding="utf-8")

