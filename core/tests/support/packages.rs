use sha2::{Digest, Sha256};
use std::{collections::BTreeMap, fs, path::Path};

pub(crate) fn payload(root: &Path) -> BTreeMap<String, Vec<u8>> {
    let names = fs::read_to_string(root.join("meta/files.list")).unwrap();
    names
        .lines()
        .chain(["meta/files.list", "meta/files.sha256"])
        .map(|path| (path.to_owned(), fs::read(root.join(path)).unwrap()))
        .collect()
}

#[cfg(all(feature = "native-tests", any(windows, target_os = "linux")))]
pub(crate) fn copy_package(source: &Path, destination: &Path) {
    for (name, bytes) in payload(source) {
        let path = destination.join(name);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, bytes).unwrap();
    }
}

pub(crate) fn package_tree(root: &Path) -> BTreeMap<String, Option<Vec<u8>>> {
    fn visit(root: &Path, directory: &Path, entries: &mut BTreeMap<String, Option<Vec<u8>>>) {
        for entry in fs::read_dir(directory).unwrap() {
            let path = entry.unwrap().path();
            let kind = fs::symlink_metadata(&path).unwrap().file_type();
            let name = path
                .strip_prefix(root)
                .unwrap()
                .to_string_lossy()
                .into_owned();
            assert!(!kind.is_symlink(), "unexpected link: {}", path.display());
            if kind.is_dir() {
                entries.insert(name, None);
                visit(root, &path, entries);
            } else {
                assert!(kind.is_file(), "unexpected entry: {}", path.display());
                entries.insert(name, Some(fs::read(path).unwrap()));
            }
        }
    }
    let mut entries = BTreeMap::new();
    visit(root, root, &mut entries);
    entries
}

pub(crate) fn assert_offline_build_readme(root: &Path, windows: bool) {
    let text = fs::read_to_string(root.join("README.md")).unwrap();
    for expected in [
        "Python 3.11 or newer",
        "real absolute executable paths",
        "`AUTOSAR_CC`",
        "`AUTOSAR_OBJDUMP`",
        "`AUTOSAR_GIT`",
        "No checkout, uv, Rust or Node is required",
        "target.json.toolchain",
        "GCC version, target triple and executable SHA-256 must all match",
        "the objdump executable must match objdump_sha256",
        "objdump --version is also queried",
        "Git has no pinned version or digest",
        "Example paths only",
        "do not guarantee the required identities",
        "new or empty external directory",
        "must not contain one another",
        "nonzero exit code",
        "`logs/`",
        "`kernel/`",
        "Preserve that directory for diagnostics",
        "cannot be retried in place",
        "another new or empty external output directory",
        "Never edit the sealed source or its hashes",
        "`python3` on Linux or `py -3` on Windows",
        "Replace angle-bracket placeholders with real paths",
    ] {
        assert!(
            text.contains(expected),
            "{}: missing {expected}",
            root.display()
        );
    }
    assert!(!text.contains("{{") && !text.contains("AUTOSAR_NM"));
    let target: serde_json::Value =
        serde_json::from_slice(&fs::read(root.join("target.json")).unwrap()).unwrap();
    let lock = &target["toolchain"];
    if windows {
        for expected in [
            "Windows x64",
            "```powershell",
            "$env:AUTOSAR_CC = 'C:\\msys64\\mingw64\\bin\\gcc.exe'",
            "$env:AUTOSAR_OBJDUMP",
            "$env:AUTOSAR_GIT",
        ] {
            assert!(text.contains(expected), "missing {expected}");
        }
        assert_eq!(
            lock["identity"],
            "gcc.exe (Rev5, Built by MSYS2 project) 16.1.0"
        );
        assert_eq!(lock["target"], "x86_64-w64-mingw32");
        assert_eq!(
            lock["objdump_sha256"],
            "c56162ea2a35f001accedce647456d296a768f457f7f1803668f8b72f6f473a8"
        );
    } else {
        for expected in [
            "Linux x64",
            "```sh",
            "export AUTOSAR_CC='/usr/bin/gcc-13'",
            "export AUTOSAR_OBJDUMP",
            "export AUTOSAR_GIT",
        ] {
            assert!(text.contains(expected), "missing {expected}");
        }
        assert_eq!(
            lock["identity"],
            "gcc (Ubuntu 13.3.0-6ubuntu2~24.04.1) 13.3.0"
        );
        assert_eq!(lock["target"], "x86_64-linux-gnu");
        assert_eq!(
            lock["objdump_sha256"],
            "325c4205a4c658a9d1e1ebc469ae55975a2b897a3d3c1e79d9b158612d37f745"
        );
    }
}

// A mutable owner ledger and recomputed seal must never authorize altered
// generated bytes or a fabricated product identity.
pub(crate) fn reseal(root: &Path) {
    let path = root.join("meta/workbench-ownership.json");
    let mut ledger: serde_json::Value = serde_json::from_slice(&fs::read(&path).unwrap()).unwrap();
    for entry in ledger["files"].as_array_mut().unwrap() {
        let bytes = fs::read(root.join(entry["path"].as_str().unwrap())).unwrap();
        entry["sha256"] = serde_json::Value::String(format!("{:x}", Sha256::digest(bytes)));
    }
    let mut bytes = serde_json::to_vec_pretty(&ledger).unwrap();
    bytes.push(b'\n');
    fs::write(path, bytes).unwrap();
    seal(root);
}

pub(crate) fn seal(root: &Path) {
    let names = fs::read_to_string(root.join("meta/files.list")).unwrap();
    let mut seal = String::new();
    for path in names.lines().chain(["meta/files.list"]) {
        seal.push_str(&format!(
            "{:x}  {path}\n",
            Sha256::digest(fs::read(root.join(path)).unwrap())
        ));
    }
    fs::write(root.join("meta/files.sha256"), seal).unwrap();
}
