def build_hierarchy_tree(wb: Workbook, instances: list[dict]) -> None:
    ws = wb.create_sheet("07_Hierarchy_Tree")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 3, "Composition Hierarchy Tree")

    ws.cell(row=3, column=1, value="Composition").font = Font(name=FONT_NAME, bold=True, size=11)
    row = 4
    for inst in instances:
        ws.cell(row=row, column=2, value=f"  {inst.get('name', '')} ({inst.get('swc_type', '')})").font = body_font()
        row += 1

    autosize(ws, {1: 28, 2: 60})


