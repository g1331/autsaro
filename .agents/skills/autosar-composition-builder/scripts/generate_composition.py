def build_port_compatibility_rules(wb: Workbook) -> None:
    ws = wb.create_sheet("09_Port_Compatibility")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 3, "Port Compatibility Rules")

    ws.cell(row=3, column=1, value="Rule").font = Font(name=FONT_NAME, bold=True, size=10)
    ws.cell(row=3, column=2, value="Description").font = Font(name=FONT_NAME, bold=True, size=10)
    rules = [
        ("R01", "Assembly connectors must link a Provided port to a Required port with compatible interface types."),
        ("R02", "Delegation connectors must map SWC port types to composition boundary port types."),
        ("R03", "Port multiplicity must be respected in assembly connector definitions."),
    ]
    for i, (rule_id, desc) in enumerate(rules, start=4):
        ws.cell(row=i, column=1, value=rule_id)
        ws.cell(row=i, column=2, value=desc)

    autosize(ws, {1: 8, 2: 80})


def build_validation_rules(wb: Workbook) -> None:
    ws = wb.create_sheet("10_Validation_Rules")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 3, "Validation Rules and Constraints")

    ws.cell(row=3, column=1, value="Check").font = Font(name=FONT_NAME, bold=True, size=10)
