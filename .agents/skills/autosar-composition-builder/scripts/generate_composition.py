"""
AUTOSAR Composition Builder — generates multi-tab AUTOSAR R22-11 Composition SWC workbook from JSON.

Usage:
    python generate_composition.py <input.json> <output.xlsx>

Input JSON schema:
{
  "item": {name, abbr, project, doc_id, revision, date, author, approver, company},
  "composition": {name, description, implementation_type},
  "swc_instances": [
    {id, name, swc_type, role, multiplicity}
  ],
  "assembly_connectors": [
    {id, source_swc, source_port, target_swc, target_port, interface_name}
  ],
  "delegation_connectors": [
    {id, swc_instance, swc_port, boundary_port, direction}  // direction: Provided|Required
  ],
  "boundary_ports": [
    {id, name, category, direction, interface_name}
  ],
  "port_compatibility_rules": [
    {rule_id, description, checks}
  ]
}
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from datetime import date as today_date

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter


# Styling
FONT_NAME = "Calibri"
NAVY = "1F3864"
LIGHT_BLUE = "D9E2F3"
ALT_ROW = "F2F2F2"
WARN_YELLOW = "FFF2CC"
GREEN_OK = "C6EFCE"
RED_BAD = "F8CBAD"
THIN = Side(border_style="thin", color="BFBFBF")
BORDER_ALL = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def title_font(size: int = 16) -> Font:
    return Font(name=FONT_NAME, size=size, bold=True, color="FFFFFF")


def header_font() -> Font:
    return Font(name=FONT_NAME, size=11, bold=True, color="FFFFFF")


def body_font() -> Font:
    return Font(name=FONT_NAME, size=10)


def style_title_row(ws, row: int, last_col: int, text: str) -> None:
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=last_col)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = title_font(14)
    cell.fill = PatternFill("solid", fgColor=NAVY)
    cell.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[row].height = 28


def style_header_row(ws, row: int, headers: list[str]) -> None:
    for col, h in enumerate(headers, start=1):
        cell = ws.cell(row=row, column=col, value=h)
        cell.font = header_font()
        cell.fill = PatternFill("solid", fgColor=NAVY)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER_ALL
    ws.row_dimensions[row].height = 32


def stripe_body(ws, start_row: int, end_row: int, last_col: int) -> None:
    for r in range(start_row, end_row + 1):
        fill = PatternFill("solid", fgColor=ALT_ROW) if (r - start_row) % 2 else None
        for c in range(1, last_col + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = body_font()
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = BORDER_ALL
            if fill:
                cell.fill = fill


def autosize(ws, widths: dict[int, int]) -> None:
    for col, width in widths.items():
        ws.column_dimensions[get_column_letter(col)].width = width


# Tab builders

def build_title_page(wb: Workbook, item: dict, composition: dict) -> None:
    ws = wb.create_sheet("00_Title_Page")
    ws.sheet_view.showGridLines = False

    style_title_row(ws, 2, 4, "AUTOSAR R22-11 Composition SWC Specification")
    style_title_row(ws, 3, 4, f"{composition.get('name', '')} ({item.get('abbr', '')})")

    fields = [
        ("Project", item.get("project", "")),
        ("Composition Name", composition.get("name", "")),
        ("Document ID", item.get("doc_id", "")),
        ("Revision", item.get("revision", "")),
        ("Date", item.get("date", str(today_date.today()))),
        ("Author", item.get("author", "")),
        ("Approver", item.get("approver", "")),
        ("Company", item.get("company", "")),
        ("AUTOSAR Version", "R22-11 (Classic Platform)"),
    ]

    row = 6
    for label, value in fields:
        ws.cell(row=row, column=2, value=label).font = Font(name=FONT_NAME, size=11, bold=True, color=NAVY)
        ws.cell(row=row, column=3, value=value).font = body_font()
        ws.cell(row=row, column=3).alignment = Alignment(horizontal="left")
        row += 1

    autosize(ws, {1: 4, 2: 22, 3: 60, 4: 4})


def build_doc_control(wb: Workbook) -> None:
    ws = wb.create_sheet("01_Document_Control")
    ws.sheet_view.showGridLines = False

    style_title_row(ws, 1, 5, "Document Control")

    style_header_row(ws, 3, ["Revision", "Date", "Author", "Description of change", "Approver"])
    placeholders = [
        ("0.1", "", "", "Initial draft generated by autosar-composition-builder", ""),
        ("0.2", "", "", "Internal review comments incorporated", ""),
        ("1.0", "", "", "Released for architecture review", ""),
    ]
    for i, row_data in enumerate(placeholders, start=4):
        for col, val in enumerate(row_data, start=1):
            ws.cell(row=i, column=col, value=val)
    stripe_body(ws, 4, 4 + len(placeholders) - 1, 5)

    style_title_row(ws, 10, 5, "Distribution List")
    style_header_row(ws, 11, ["Name", "Role", "Organization", "Email", "Notes"])
    for i in range(12, 16):
        for c in range(1, 6):
            ws.cell(row=i, column=c, value="")
    stripe_body(ws, 12, 15, 5)

    autosize(ws, {1: 12, 2: 14, 3: 22, 4: 50, 5: 22})


def build_composition_identity(wb: Workbook, item: dict, composition: dict) -> None:
    ws = wb.create_sheet("02_Composition_Identity")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 4, "Composition Identity")

    fields = [
        ("Composition Name", composition.get("name", "")),
        ("Abbreviation", item.get("abbr", "")),
        ("Description", composition.get("description", "")),
        ("Implementation Type", composition.get("implementation_type", "Software")),
        ("Vendor/Owner", item.get("company", "")),
    ]

    row = 3
    for label, value in fields:
        ws.cell(row=row, column=1, value=label).font = Font(name=FONT_NAME, bold=True, size=10)
        ws.cell(row=row, column=2, value=value).font = body_font()
        ws.cell(row=row, column=2).alignment = Alignment(wrap_text=True, vertical="top")
        row += 1

    autosize(ws, {1: 22, 2: 60})


def build_swc_instances(wb: Workbook, instances: list[dict]) -> None:
    ws = wb.create_sheet("03_SWC_Instances")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 5, "Contained SWC Instances")

    style_header_row(ws, 3, ["Instance ID", "Instance Name", "SWC Type", "Role", "Multiplicity"])
    if not instances:
        instances = []
    for i, inst in enumerate(instances, start=4):
        ws.cell(row=i, column=1, value=inst.get("id", ""))
        ws.cell(row=i, column=2, value=inst.get("name", ""))
        ws.cell(row=i, column=3, value=inst.get("swc_type", ""))
        ws.cell(row=i, column=4, value=inst.get("role", ""))
        ws.cell(row=i, column=5, value=inst.get("multiplicity", "1"))
    if instances:
        stripe_body(ws, 4, 3 + len(instances), 5)

    autosize(ws, {1: 14, 2: 24, 3: 24, 4: 16, 5: 14})


def build_assembly_connectors(wb: Workbook, connectors: list[dict]) -> None:
    ws = wb.create_sheet("04_Assembly_Connectors")
    ws.sheet_view.showGridLines = False
    style_title_row(ws, 1, 6, "Assembly Connectors (SWC-to-SWC Port Mappings)")

    style_header_row(ws, 3, ["Connector ID", "Source SWC", "Source Port", "Target SWC", "Target Port", "Interface"])
    if not connectors:
        connectors = []
    for i, conn in enumerate(connectors, start=4):
        ws.cell(row=i, column=1, value=conn.get("id", ""))
        ws.cell(row=i, column=2, value=conn.get("source_swc", ""))
        ws.cell(row=i, column=3, value=conn.get("source_port", ""))
        ws.cell(row=i, column=4, value=conn.get("target_swc", ""))
        ws.cell(row=i, column=5, value=conn.get("target_port", ""))
        ws.cell(row=i, column=6, value=conn.get("interface_name", ""))
    if connectors:
        stripe_body(ws, 4, 3 + len(connectors), 6)

    autosize(ws, {1: 14, 2: 18, 3: 18, 4: 18, 5: 18, 6: 24})


